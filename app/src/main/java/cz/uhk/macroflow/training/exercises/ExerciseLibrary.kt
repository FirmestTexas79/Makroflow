/**
 * Atlas svalů a knihovna cviků (čistý Kotlin, pokryto testy). Podklady v docs/adr/0019.
 *
 * Anatomické názvy podle Terminologia Anatomica (latinsky, „m.“ = musculus, „mm.“ = musculi).
 * Technika je psaná pro běžného návštěvníka posilovny – bezpečná výchozí varianta cviku.
 */
enum class Equipment(val label: String) {
    BARBELL("osa"), DUMBBELL("jednoručky"), CABLE("kladka"), MACHINE("stroj"),
    BODYWEIGHT("vlastní váha"), BAR("hrazda / bradla"), OTHER("jiné")
}

data class Exercise(
    val id: String,
    val name: String,
    /** Běžný (často anglický) název, pod kterým cvik lidé znají. */
    val alias: String,
    val equipment: Equipment,
    /** 1 = začátečník, 2 = mírně pokročilý, 3 = pokročilý. */
    val level: Int,
    val primary: Set<Muscle>,
    val secondary: Set<Muscle>,
    val latinPrimary: List<String>,
    val latinSecondary: List<String>,
    val steps: List<String>,
    val tips: List<String>,
    val mistakes: List<String>
) {
    val levelLabel: String get() = when (level) { 1 -> "začátečník"; 2 -> "mírně pokročilý"; else -> "pokročilý" }
    fun works(m: Muscle) = m in primary || m in secondary
}

