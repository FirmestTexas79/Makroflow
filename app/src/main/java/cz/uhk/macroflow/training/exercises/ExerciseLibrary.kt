    private val byId = ALL.associateBy { it.id }

    fun byId(id: String): Exercise? = byId[id]

    /** Cviky pro partii: nejdřív ty, kde je partie hlavní, pak vedlejší; v rámci skupiny podle obtížnosti. */
    fun forMuscle(m: Muscle): List<Exercise> =
        ALL.filter { m in it.primary }.sortedBy { it.level } + ALL.filter { m !in it.primary && m in it.secondary }.sortedBy { it.level }
}
